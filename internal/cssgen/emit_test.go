func formatted(t *testing.T, src []byte) string {
	t.Helper()
	out, err := format.Source(src)
	if err != nil {
		t.Fatalf("format.Source rejects the output: %v\n%s", err, src)
	}
	return string(out)
}

func emitted(t *testing.T, emit func(*model) []byte) string {
	t.Helper()
	m, _ := loadFixtureModel(t)
	return formatted(t, emit(m))
}

func expectContains(t *testing.T, src string, wants ...string) {
	t.Helper()
	for _, want := range wants {
		if !strings.Contains(src, want) {
			t.Errorf("output does not contain %q", want)
		}
	}
}

func expectAbsent(t *testing.T, src string, unwanted ...string) {
	t.Helper()
	for _, u := range unwanted {
		if strings.Contains(src, u) {
			t.Errorf("output contains %q", u)
		}
	}
}

func declarations(t *testing.T, src string) []string {
	t.Helper()
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "", src, 0)
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	text := func(from, to token.Pos) string {
		return strings.TrimSpace(src[fset.Position(from).Offset:fset.Position(to).Offset])
	}
	var decls []string
	for _, d := range file.Decls {
		switch d := d.(type) {
		case *ast.FuncDecl:
			decls = append(decls, text(d.Pos(), d.Body.Lbrace))
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				switch spec := spec.(type) {
				case *ast.TypeSpec:
					decls = append(decls, "type "+spec.Name.Name)
				case *ast.ValueSpec:
					decls = append(decls, d.Tok.String()+" "+text(spec.Pos(), spec.End()))
				}
			}
		}
	}
	return decls
}

func TestEveryEmittedFile(t *testing.T) {
	m, _ := loadFixtureModel(t)
	again, _ := loadFixtureModel(t)
	for _, e := range emitters {
		t.Run(e.name, func(t *testing.T) {
			src := e.emit(m)
			if !bytes.HasPrefix(src, []byte(generatedHeader)) {
				t.Errorf("output does not start with the header line:\n%s", src)
			}
			formatted(t, src)
			for i, line := range strings.Split(string(src), "\n")[1:] {
				if strings.Contains(line, "//") {
					t.Errorf("line %d carries a comment: %q", i+2, line)
				}
			}
			file, err := parser.ParseFile(token.NewFileSet(), "", src, parser.ParseComments)
			if err != nil {
				t.Fatalf("parse: %v", err)
			}
			var comments []string
			for _, group := range file.Comments {
				for _, c := range group.List {
					comments = append(comments, c.Text)
				}
			}
			expectLines(t, "comments", comments, []string{strings.TrimSuffix(generatedHeader, "\n")})
			if !bytes.Equal(src, e.emit(again)) {
				t.Error("two emissions from equal models differ")
			}
		})
	}
}

