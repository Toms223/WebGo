func TestWriteFormatted(t *testing.T) {
	path := filepath.Join(t.TempDir(), "nested", "x_gen.go")
	if err := writeFormatted(path, []byte("package x\nfunc  F( ) {}\n")); err != nil {
		t.Fatalf("writeFormatted: %v", err)
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if want := "package x\n\nfunc F() {}\n"; string(got) != want {
		t.Errorf("written = %q, want %q", got, want)
	}

	bad := filepath.Join(t.TempDir(), "bad_gen.go")
	err = writeFormatted(bad, []byte("package x\nfunc {"))
	if err == nil {
		t.Fatal("writeFormatted accepted invalid Go")
	}
	if !strings.Contains(err.Error(), bad) {
		t.Errorf("error %q does not name the file", err)
	}
	if _, statErr := os.Stat(bad); !os.IsNotExist(statErr) {
		t.Errorf("invalid Go was written to %s", bad)
	}
}

func stage(t *testing.T, from, to string) {
	t.Helper()
	data, err := os.ReadFile(from)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(to), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(to, data, 0o644); err != nil {
		t.Fatal(err)
	}
}

func offline(t *testing.T) {
	t.Helper()
	server := httptest.NewServer(http.NotFoundHandler())
	registry := npm.Registry
	npm.Registry = server.URL
	t.Cleanup(func() {
		npm.Registry = registry
		server.Close()
	})
}

