package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
)

const header = "// Code generated by cssgen. DO NOT EDIT.\n"

const cssImport = "github.com/Toms223/WebGo/css"

func source(pkg string, imports ...string) *bytes.Buffer {
	b := &bytes.Buffer{}
	fmt.Fprintf(b, "%s\npackage %s\n", header, pkg)
	for _, path := range imports {
		fmt.Fprintf(b, "\nimport %q\n", path)
	}
	return b
}

func markerInterface(b *bytes.Buffer, name, embedded, marker string) {
	fmt.Fprintf(b, "\ntype %s interface {\n\t%s\n\t%s()\n}\n", name, embedded, marker)
}

func markerMethod(b *bytes.Buffer, receiver, marker string) {
	fmt.Fprintf(b, "func (%s) %s() {}\n", receiver, marker)
}

func cssMarker(goName string) string { return "CSS" + goName }

func mediaMarker(goName string) string { return "Media" + goName }

func styleMarker(goName string) string { return "Style" + goName }

func descriptorMarker(goName string) string { return "Descriptor" + goName }

func containerMarker(goName string) string { return "Container" + goName }

func writeFormatted(path string, src []byte) error {
	formatted, err := format.Source(src)
	if err != nil {
		return fmt.Errorf("cssgen: %s is not valid Go: %w", path, err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("cssgen: %w", err)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		return fmt.Errorf("cssgen: %w", err)
	}
	return nil
}
